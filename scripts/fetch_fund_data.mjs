// Makes sure data/fund-data.ts exists before the app builds, runs or tests.
//
// The real fund holdings come from BlackRock and State Street, whose terms don't
// allow republishing them. So they live in a private GitHub repo, not this public one:
//   1. data/fund-data.ts already exists (your own copy): leave it alone.
//   2. FUND_DATA_TOKEN is set (on Vercel): download it from the private repo.
//      If that fails, stop the build, so the live site never ships sample data.
//   3. On Vercel without a token: stop the build.
//   4. Otherwise (someone else's clone): write a small made-up sample, so the app
//      and tests still run without publishing anyone's data.
//
// Never prints the token.
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), "..", "data", "fund-data.ts");
const REPO = process.env.FUND_DATA_REPO ?? "nancyli15/etf-lookthrough-data";
const FILE = "fund-data.ts";

// Made-up weights for a few large companies. Not any fund's real holdings.
const SAMPLE = `// Sample data, written by scripts/fetch_fund_data.mjs because the real fund data
// isn't available here. The weights are made up: they are not SPY's real holdings.
import type { Fund } from "./fund-types";

export const FUND_DATA_IS_SAMPLE = true;

export const FUND_DATA: Record<string, Fund> = {
  "SPY": {
    "symbol": "SPY",
    "name": "SPDR S&P 500 ETF (sample data, not real holdings)",
    "asOf": "2026-01-01",
    "source": "sample",
    "nonCompanyWeight": 0.75,
    "holdings": [
      {"symbol": "AAPL", "name": "APPLE INC", "weight": 0.07},
      {"symbol": "NVDA", "name": "NVIDIA CORP", "weight": 0.07},
      {"symbol": "MSFT", "name": "MICROSOFT CORP", "weight": 0.06},
      {"symbol": "AMZN", "name": "AMAZON.COM INC", "weight": 0.05}
    ]
  },
};
`;

async function download(token) {
  const response = await fetch(`https://api.github.com/repos/${REPO}/contents/${FILE}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      // "raw" returns the file itself, and works for files over 1 MB.
      Accept: "application/vnd.github.raw+json",
      "X-GitHub-Api-Version": "2022-11-28",
    },
  });
  if (!response.ok) throw new Error(`GitHub returned ${response.status} for ${REPO}/${FILE}`);
  const text = await response.text();
  // Only accept what scripts/build_funds.py writes, not an error page or a wrong file.
  if (!text.startsWith("// Generated by scripts/build_funds.py") || !text.includes("export const FUND_DATA")) {
    throw new Error(`${REPO}/${FILE} doesn't look like generated fund data`);
  }
  return text;
}

if (existsSync(OUTPUT)) {
  console.log("Fund data: using the existing data/fund-data.ts");
} else if (process.env.FUND_DATA_TOKEN) {
  try {
    writeFileSync(OUTPUT, await download(process.env.FUND_DATA_TOKEN));
    console.log(`Fund data: downloaded from the private repo ${REPO}`);
  } catch (err) {
    console.error(`Fund data: download failed. ${err instanceof Error ? err.message : ""}`);
    process.exit(1);
  }
} else if (process.env.VERCEL) {
  // Vercel sets VERCEL=1 during builds. The live site must never get sample data.
  console.error("Fund data: FUND_DATA_TOKEN isn't set in Vercel, so the real fund data can't be downloaded.");
  process.exit(1);
} else {
  writeFileSync(OUTPUT, SAMPLE);
  console.log("Fund data: no real data here, so wrote made-up sample data (see scripts/fetch_fund_data.mjs)");
}
